export const LANGUAGES = { en };
let current = en;

export function setLanguage(code) {
  current = LANGUAGES[code] || en;
}

function lookup(dict, key) {
  return key.split('.').reduce((o, p) => (o && typeof o === 'object' ? o[p] : undefined), dict);
}

// The text for `key`, with {placeholders} filled from `vars`. Missing text
// falls back to English, then to the key itself (and a warning in the console).
export function t(key, vars) {
  let text = lookup(current, key);
  if (typeof text !== 'string') text = lookup(en, key);
  if (typeof text !== 'string') {
    console.warn(`Missing text: ${key}`);
    return key;
  }
  return vars ? text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined && vars[k] !== null ? String(vars[k]) : m)) : text;
}
